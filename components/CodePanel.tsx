/**
 * Resolves only the dependencies that this specific app actually requires.
 * Prevents Sandpack from timing out by avoiding downloading 20+ heavy unused packages.
 */
function resolveAppDependencies(fileData: FileData | null): Record<string, string> {
  const deps: Record<string, string> = {
    "lucide-react": "^1.16.0",
  };

  // 1. Include explicit dependencies generated by AI, normalizing "latest" to cached pinned versions
  if (fileData?.dependencies) {
    for (const [pkg, ver] of Object.entries(fileData.dependencies)) {
      if (ver && ver !== "latest") {
        deps[pkg] = ver;
      } else {
        deps[pkg] = KNOWN_DEPENDENCIES[pkg] || "^1.0.0";
      }
    }
  }

  // 2. Scan file source code for any imported packages
  if (fileData?.files) {
    const allCode = Object.values(fileData.files)
      .map((f) => (typeof f === "object" && f && "code" in f ? f.code : ""))
      .join("\n");

    for (const [pkg, ver] of Object.entries(KNOWN_DEPENDENCIES)) {
      if (!deps[pkg]) {
        const escaped = pkg.replace(/[-/\\^$*+?.()|[\]{}]/g, "\\$&");
        if (new RegExp(`from\\s+['"]${escaped}(?:/.*)?['"]`, "m").test(allCode)) {
          deps[pkg] = ver;
        }
      }
    }
  }

  return deps;
}

